import { iconUrl } from '../decks/deckIcons';

/**
 * Creates a demo project with procedurally generated card artwork built from
 * the free Fractal Symbols icon library (Felix Thalin, CC BY 4.0). Each card
 * is drawn on a canvas — a large colored icon plus a label — and stored as a
 * PNG blob, exactly like a real imported asset.
 */

const DEMO_ICONS: Array<{ id: string; label: string; color: string }> = [
  { id: 'dice', label: 'Dice', color: '#1769ff' },
  { id: 'axe', label: 'Axe', color: '#c23b43' },
  { id: 'shield', label: 'Shield', color: '#2f7d4f' },
  { id: 'castle', label: 'Castle', color: '#7a5af0' },
  { id: 'flask', label: 'Flask', color: '#b45309' },
  { id: 'star', label: 'Star', color: '#334155' }
];

function loadSvgImage(svgText: string): Promise<HTMLImageElement> {
  const dataUrl = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svgText)}`;
  return new Promise((resolve, reject) => {
    const image = new Image();
    image.onload = () => resolve(image);
    image.onerror = () => reject(new Error('Could not decode icon SVG'));
    image.src = dataUrl;
  });
}

async function renderCardCanvas(icon: { id: string; label: string; color: string }): Promise<Blob> {
  const svgText = await (await fetch(iconUrl(icon.id))).text();
  const coloredSvg = svgText.replace(/currentColor/g, icon.color);
  const image = await loadSvgImage(coloredSvg);

  const canvas = document.createElement('canvas');
  canvas.width = 635;
  canvas.height = 889;
  const ctx = canvas.getContext('2d');
  if (!ctx) throw new Error('Canvas unavailable');

  // Card background and border.
  ctx.fillStyle = '#f6f1e7';
  ctx.fillRect(0, 0, canvas.width, canvas.height);
  ctx.strokeStyle = '#c0b8a8';
  ctx.lineWidth = 8;
  ctx.strokeRect(20, 20, canvas.width - 40, canvas.height - 40);

  // Corner accents (small dots in the icon color).
  ctx.fillStyle = icon.color;
  for (const [x, y] of [[60, 60], [canvas.width - 60, 60], [60, canvas.height - 60], [canvas.width - 60, canvas.height - 60]] as const) {
    ctx.beginPath();
    ctx.arc(x, y, 14, 0, Math.PI * 2);
    ctx.fill();
  }

  // Large centered icon.
  const maxIconWidth = 360;
  const maxIconHeight = 430;
  const scale = Math.min(maxIconWidth / image.width, maxIconHeight / image.height);
  const drawWidth = image.width * scale;
  const drawHeight = image.height * scale;
  ctx.drawImage(image, (canvas.width - drawWidth) / 2, 240 + (maxIconHeight - drawHeight) / 2, drawWidth, drawHeight);

  // Label.
  ctx.fillStyle = '#2b2b2b';
  ctx.font = 'bold 64px sans-serif';
  ctx.fillText(icon.label, 40, 110);
  ctx.font = '40px sans-serif';
  ctx.fillStyle = '#6b6455';
  ctx.fillText('Demo card', 40, 170);

  return new Promise<Blob>((resolve, reject) =>
    canvas.toBlob((blob) => (blob ? resolve(blob) : reject(new Error('toBlob failed'))), 'image/png')
  );
}

export async function createDemoProject(): Promise<string> {
  const project = await createProject('Demo Deck', 'Original demo generated by Deal With It.');
  const now = Date.now();
  let deck = createDeck(project.id, 'Demo Deck');

  for (let i = 0; i < DEMO_ICONS.length; i++) {
    const icon = DEMO_ICONS[i];
    const canvasBlob = await renderCardCanvas(icon);

    // Keep the canvas dimensions for asset metadata.
    const probe = await new Promise<{ width: number; height: number }>((resolve) => {
      const img = new Image();
      img.onload = () => resolve({ width: img.width, height: img.height });
      img.src = URL.createObjectURL(canvasBlob);
    });

    const assetId = crypto.randomUUID();
    await saveImageAsset(
      {
        id: assetId,
        projectId: project.id,
        blobKey: crypto.randomUUID(),
        filename: `demo-card-${icon.label}.png`,
        mime: 'image/png',
        widthPx: probe.width,
        heightPx: probe.height,
        sha256: `demo-${icon.id}`,
        createdAt: now
      },
      canvasBlob
    );

    const thumbnail = await makeThumbnail(canvasBlob);
    if (thumbnail) {
      await saveThumbnail({
        assetId,
        projectId: project.id,
        dataUrl: thumbnail,
        widthPx: probe.width,
        heightPx: probe.height
      });
    }

    const cardId = crypto.randomUUID();
    await saveCardDefinition({
      id: cardId,
      projectId: project.id,
      name: icon.label,
      frontAssetId: assetId,
      frontTransform: DEFAULT_TRANSFORM,
      widthMm: 63.5,
      heightMm: 88.9,
      tags: ['demo']
    });

    deck = addEntryToDeck(deck, cardId, 3);
  }

  await saveDeck(deck);
  await saveTable({
    id: crypto.randomUUID(),
    projectId: project.id,
    name: 'Main table',
    objects: [],
    camera: { x: 0, y: 0, zoom: 1 },
    background: '#4a5b4f',
    updatedAt: now
  });
  await touchProject(project.id);
  return project.id;
}
