import {
  createProject,
  saveCardDefinition,
  saveDeck,
  saveImageAsset,
  saveTable,
  touchProject
} from '../../persistence/repositories';
import { addEntryToDeck, createDeck } from '../../domain/deck-operations';
import { DEFAULT_TRANSFORM } from '../../domain/transforms';

/**
 * Creates an original demo project with procedurally generated artwork
 * (no third-party or copyrighted imagery). Each card is drawn on a canvas
 * and stored as a PNG blob, exactly like a real imported asset.
 */
export async function createDemoProject(): Promise<string> {
  const project = await createProject('Demo Deck', 'Original demo generated by Deal With It.');
  const now = Date.now();
  let deck = createDeck(project.id, 'Demo Deck');
  const suits = ['Spades', 'Hearts', 'Clubs', 'Diamonds', 'Jokers', 'Triads'];

  for (let i = 0; i < 6; i++) {
    const canvas = document.createElement('canvas');
    canvas.width = 635;
    canvas.height = 889;
    const ctx = canvas.getContext('2d');
    if (!ctx) throw new Error('Canvas unavailable');
    ctx.fillStyle = '#f6f1e7';
    ctx.fillRect(0, 0, canvas.width, canvas.height);
    ctx.fillStyle = '#2b2b2b';
    ctx.font = 'bold 64px sans-serif';
    ctx.fillText(suits[i], 40, 90);
    ctx.font = '40px sans-serif';
    ctx.fillText(`Card ${i + 1}`, 40, 160);
    ctx.strokeStyle = '#c0b8a8';
    ctx.lineWidth = 8;
    ctx.strokeRect(20, 20, canvas.width - 40, canvas.height - 40);

    const blob = await new Promise<Blob>((resolve, reject) =>
      canvas.toBlob((b) => (b ? resolve(b) : reject(new Error('toBlob failed'))), 'image/png')
    );

    const assetId = crypto.randomUUID();
    await saveImageAsset(
      {
        id: assetId,
        projectId: project.id,
        blobKey: crypto.randomUUID(),
        filename: `demo-card-${i + 1}.png`,
        mime: 'image/png',
        widthPx: canvas.width,
        heightPx: canvas.height,
        sha256: `demo-${i + 1}`,
        createdAt: now
      },
      blob
    );

    const cardId = crypto.randomUUID();
    await saveCardDefinition({
      id: cardId,
      projectId: project.id,
      name: `${suits[i]} ${i + 1}`,
      frontAssetId: assetId,
      frontTransform: DEFAULT_TRANSFORM,
      widthMm: 63.5,
      heightMm: 88.9,
      tags: ['demo']
    });

    deck = addEntryToDeck(deck, cardId, 3);
  }

  await saveDeck(deck);
  await saveTable({
    id: crypto.randomUUID(),
    projectId: project.id,
    name: 'Main table',
    objects: [],
    camera: { x: 0, y: 0, zoom: 1 },
    background: '#4a5b4f',
    updatedAt: now
  });
  await touchProject(project.id);
  return project.id;
}
